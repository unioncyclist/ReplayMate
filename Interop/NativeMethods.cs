    public const int NIF_INFO = 0x10;

    public const int NIIF_INFO = 0x1;
    public const int NIIF_WARNING = 0x2;

    public const int WM_LBUTTONUP = 0x0202;
    public const int WM_RBUTTONUP = 0x0205;

    public const int IMAGE_ICON = 1;
    public const int LR_LOADFROMFILE = 0x10;
    public const int LR_DEFAULTSIZE = 0x40;

    public const int MF_STRING = 0x0;
    public const int MF_SEPARATOR = 0x800;
    public const int MF_GRAYED = 0x1;
    public const int MF_CHECKED = 0x8;

    public const int TPM_RIGHTBUTTON = 0x2;
    public const int TPM_RETURNCMD = 0x100;
